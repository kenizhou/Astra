//! The snippet store: the identity, the row types, and the CRUD the
//! composer's picker and the CLI drive over [`AiStore`]. One row is one
//! reusable text block the writer keeps: title and body are the
//! writer's own, never model-derived. The list reads the most recently
//! touched first, so a snippet the writer just fixed surfaces first in
//! the picker; an update rewrites the fields and touches `updated_at`,
//! the stamp the ordering rides.

use crate::store::AiStore;
use crate::AiStoreError;

/// The identity of one stored snippet. Generated by the caller as a v4
/// UUID (the [`RuleId`](crate::RuleId) spelling) so a snippet exists as
/// data before it is stored.
#[derive(Debug, Clone, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub struct SnippetId(String);

impl SnippetId {
    /// Wraps an existing id string.
    pub fn new(value: String) -> Self {
        Self(value)
    }

    /// Generates a fresh snippet id (a v4 UUID).
    pub fn generate() -> Self {
        Self(uuid::Uuid::new_v4().to_string())
    }

    /// The id string.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl std::fmt::Display for SnippetId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

/// One snippet to insert: every column the caller owns; the store
/// stamps `created_at` and the first `updated_at` itself.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NewSnippet {
    /// The snippet's identity.
    pub id: SnippetId,
    /// The snippet's short title, the picker's label.
    pub title: String,
    /// The snippet's body, the text an insert places at the cursor.
    pub body: String,
}

/// One snippet as the store reads it back: every column of the
/// `snippets` table, `created_at` and `updated_at` set by the store
/// itself. Serialisable so the CLI can carry rows across the process
/// boundary.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct SnippetRow {
    /// The snippet's identity.
    pub id: SnippetId,
    /// The snippet's short title.
    pub title: String,
    /// The snippet's body.
    pub body: String,
    /// The store's creation stamp (unix seconds).
    pub created_at: i64,
    /// The store's touch stamp (unix seconds), fresh on every update;
    /// the list's recency ordering rides it.
    pub updated_at: i64,
}

impl AiStore {
    /// Inserts one snippet and answers the row as it landed, the
    /// store's `created_at` and first `updated_at` stamps included.
    /// The caller mints ids, so an id collision is a caller bug, not a
    /// store state to paper over.
    ///
    /// # Errors
    /// Fails when the insert cannot run.
    pub fn insert_snippet(&self, snippet: &NewSnippet) -> Result<SnippetRow, AiStoreError> {
        let conn = self.lock();
        conn.query_row(
            "INSERT INTO snippets (
                 id, title, body, created_at, updated_at
             ) VALUES (
                 ?1, ?2, ?3, strftime('%s','now'), strftime('%s','now')
             )
             RETURNING id, title, body, created_at, updated_at",
            rusqlite::params![snippet.id.as_str(), snippet.title, snippet.body],
            |row| {
                Ok(SnippetRow {
                    id: SnippetId::new(row.get(0)?),
                    title: row.get(1)?,
                    body: row.get(2)?,
                    created_at: row.get(3)?,
                    updated_at: row.get(4)?,
                })
            },
        )
        .map_err(AiStoreError::Sqlite)
    }

    /// Every snippet, the most recently touched first (the touch stamp,
    /// then id, so same-second rows still order deterministically): the
    /// read the composer's picker and the CLI's listing share. An empty
    /// answer names a library with no snippets yet.
    ///
    /// # Errors
    /// Fails when the query cannot run.
    pub fn list_snippets(&self) -> Result<Vec<SnippetRow>, AiStoreError> {
        let conn = self.lock();
        let mut statement = conn
            .prepare(
                "SELECT id, title, body, created_at, updated_at
                 FROM snippets
                 ORDER BY updated_at DESC, id DESC",
            )
            .map_err(AiStoreError::Sqlite)?;
        let rows = statement
            .query_map([], |row| {
                Ok(SnippetRow {
                    id: SnippetId::new(row.get(0)?),
                    title: row.get(1)?,
                    body: row.get(2)?,
                    created_at: row.get(3)?,
                    updated_at: row.get(4)?,
                })
            })
            .map_err(AiStoreError::Sqlite)?;
        rows.collect::<Result<Vec<_>, _>>()
            .map_err(AiStoreError::Sqlite)
    }

    /// Rewrites one snippet's title and body and touches `updated_at`:
    /// the touch is the recency the picker's ordering rides, so an
    /// edited snippet resurfaces first. Returns whether any row
    /// changed: `false` names an id no snippet carries, for the caller
    /// to report.
    ///
    /// # Errors
    /// Fails when the update cannot run.
    pub fn update_snippet(
        &self,
        id: &SnippetId,
        title: &str,
        body: &str,
    ) -> Result<bool, AiStoreError> {
        let conn = self.lock();
        conn.execute(
            "UPDATE snippets
             SET title = ?2, body = ?3, updated_at = strftime('%s','now')
             WHERE id = ?1",
            rusqlite::params![id.as_str(), title, body],
        )
        .map(|changed| changed > 0)
        .map_err(AiStoreError::Sqlite)
    }

    /// Deletes one snippet. Returns whether any row went: `false`
    /// names an id no snippet carried, for the caller to report.
    ///
    /// # Errors
    /// Fails when the delete cannot run.
    pub fn delete_snippet(&self, id: &SnippetId) -> Result<bool, AiStoreError> {
        let conn = self.lock();
        conn.execute(
            "DELETE FROM snippets WHERE id = ?1",
            rusqlite::params![id.as_str()],
        )
        .map(|changed| changed > 0)
        .map_err(AiStoreError::Sqlite)
    }
}
