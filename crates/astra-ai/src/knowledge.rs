//! The knowledge store: the identity, the row types, and the CRUD the
//! extraction job and the CLI drive over [`AiStore`]. One row is one
//! model-derived entry the account's drafts are shaped with: its kind
//! and text, the message it was extracted from, and the correlation id
//! of the extraction turn. Entries never auto-delete; forgetting is the
//! caller's explicit verb. The kind rides as the caller's wire word
//! (the closed set is the extraction prompt's, pinned in astra-app),
//! and the exact-text dedup guard lives in the table's unique index on
//! (account, text): an insert whose account already holds the text
//! refuses loudly, so a repeated extraction never stacks entries.

use crate::correlation::CorrelationId;
use crate::store::AiStore;
use crate::AiStoreError;

/// The identity of one stored knowledge entry. Generated by the caller
/// as a v4 UUID (the [`RuleId`](crate::RuleId) spelling) so an entry
/// exists as data before it is stored.
#[derive(Debug, Clone, PartialEq, Eq, Hash, serde::Serialize, serde::Deserialize)]
pub struct KnowledgeId(String);

impl KnowledgeId {
    /// Wraps an existing id string.
    pub fn new(value: String) -> Self {
        Self(value)
    }

    /// Generates a fresh knowledge id (a v4 UUID).
    pub fn generate() -> Self {
        Self(uuid::Uuid::new_v4().to_string())
    }

    /// The id string.
    pub fn as_str(&self) -> &str {
        &self.0
    }
}

impl std::fmt::Display for KnowledgeId {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(&self.0)
    }
}

/// One knowledge entry to insert: every column the caller owns; the
/// store stamps `created_at` itself.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct NewKnowledgeEntry {
    /// The entry's identity.
    pub id: KnowledgeId,
    /// The account the entry belongs to and shapes.
    pub account: String,
    /// The entry's kind: the extraction vocabulary's wire word.
    pub kind: String,
    /// The entry's text, the exact string the dedup guard keys on.
    pub text: String,
    /// The account owning the message the entry was extracted from.
    pub source_message_account: String,
    /// The source message's provider key, unique within its account.
    pub source_message_key: String,
    /// The extraction turn the entry rode.
    pub correlation: CorrelationId,
}

/// One knowledge entry as the store reads it back: every column of the
/// `knowledge` table, `created_at` set by the store itself at insert.
/// Serialisable so the CLI can carry rows across the process boundary.
#[derive(Debug, Clone, PartialEq, Eq, serde::Serialize, serde::Deserialize)]
pub struct KnowledgeEntryRow {
    /// The entry's identity.
    pub id: KnowledgeId,
    /// The account the entry belongs to.
    pub account: String,
    /// The entry's kind: the extraction vocabulary's wire word.
    pub kind: String,
    /// The entry's text.
    pub text: String,
    /// The account owning the message the entry was extracted from.
    pub source_message_account: String,
    /// The source message's provider key.
    pub source_message_key: String,
    /// The extraction turn the entry rode.
    pub correlation: CorrelationId,
    /// The store's creation stamp (unix seconds).
    pub created_at: i64,
}

impl AiStore {
    /// Inserts one knowledge entry and answers the row as it landed,
    /// the store's `created_at` stamp included. The exact-text dedup
    /// guard refuses loudly: the unique index on (account, text) fails
    /// an insert whose account already holds the same text, so a
    /// repeated extraction surfaces as an error rather than a second
    /// row. The caller mints ids, so an id collision is a caller bug,
    /// not a store state to paper over.
    ///
    /// # Errors
    /// Fails when the insert cannot run, the dedup guard included.
    pub fn insert_knowledge(
        &self,
        entry: &NewKnowledgeEntry,
    ) -> Result<KnowledgeEntryRow, AiStoreError> {
        let conn = self.lock();
        conn.query_row(
            "INSERT INTO knowledge (
                 id, account, kind, text, source_message_account,
                 source_message_key, correlation_id, created_at
             ) VALUES (
                 ?1, ?2, ?3, ?4, ?5, ?6, ?7, strftime('%s','now')
             )
             RETURNING id, account, kind, text, source_message_account,
                       source_message_key, correlation_id, created_at",
            rusqlite::params![
                entry.id.as_str(),
                entry.account,
                entry.kind,
                entry.text,
                entry.source_message_account,
                entry.source_message_key,
                entry.correlation.as_str(),
            ],
            |row| {
                Ok(KnowledgeEntryRow {
                    id: KnowledgeId::new(row.get(0)?),
                    account: row.get(1)?,
                    kind: row.get(2)?,
                    text: row.get(3)?,
                    source_message_account: row.get(4)?,
                    source_message_key: row.get(5)?,
                    correlation: CorrelationId::new(row.get(6)?),
                    created_at: row.get(7)?,
                })
            },
        )
        .map_err(AiStoreError::Sqlite)
    }

    /// Every entry one account holds, newest first (creation time, then
    /// id, so same-second inserts still order deterministically): the
    /// read the draft prompt's knowledge context and the CLI's listing
    /// share. An empty answer names an account no extraction has
    /// touched.
    ///
    /// # Errors
    /// Fails when the query cannot run.
    pub fn knowledge_for_account(
        &self,
        account: &str,
    ) -> Result<Vec<KnowledgeEntryRow>, AiStoreError> {
        let conn = self.lock();
        let mut statement = conn
            .prepare(
                "SELECT id, account, kind, text, source_message_account,
                        source_message_key, correlation_id, created_at
                 FROM knowledge
                 WHERE account = ?1
                 ORDER BY created_at DESC, id DESC",
            )
            .map_err(AiStoreError::Sqlite)?;
        let rows = statement
            .query_map(rusqlite::params![account], |row| {
                Ok(KnowledgeEntryRow {
                    id: KnowledgeId::new(row.get(0)?),
                    account: row.get(1)?,
                    kind: row.get(2)?,
                    text: row.get(3)?,
                    source_message_account: row.get(4)?,
                    source_message_key: row.get(5)?,
                    correlation: CorrelationId::new(row.get(6)?),
                    created_at: row.get(7)?,
                })
            })
            .map_err(AiStoreError::Sqlite)?;
        rows.collect::<Result<Vec<_>, _>>()
            .map_err(AiStoreError::Sqlite)
    }

    /// Deletes one knowledge entry. Entries never auto-delete, so this
    /// is the only exit. Returns whether any row went: `false` names an
    /// id no entry carried, for the caller to report.
    ///
    /// # Errors
    /// Fails when the delete cannot run.
    pub fn forget_knowledge(&self, id: &KnowledgeId) -> Result<bool, AiStoreError> {
        let conn = self.lock();
        conn.execute(
            "DELETE FROM knowledge WHERE id = ?1",
            rusqlite::params![id.as_str()],
        )
        .map(|changed| changed > 0)
        .map_err(AiStoreError::Sqlite)
    }
}
