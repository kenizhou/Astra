import { build } from 'esbuild';
import { cpSync, readFileSync, writeFileSync } from 'node:fs';
import { patchPiBundle, PI_BUNDLE_EXTERNALS } from './scripts/patch-bundle.mjs';

const outfile = 'dist/index.cjs';
await build({
  entryPoints: ['src/index.ts'],
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node22',
  outfile,
  external: PI_BUNDLE_EXTERNALS,
  banner: { js: '// GENERATED by esbuild; do not edit (source: sidecar/src/)' },
  logLevel: 'info',
});

// The pi SDK needs post-build patches to run from a single-file CJS bundle
// (import_meta shim plus package.json inline; see scripts/patch-bundle.mjs).
writeFileSync(outfile, patchPiBundle(readFileSync(outfile, 'utf8'), 'node_modules/@earendil-works/pi-coding-agent'));

// Ship the skill guide beside the bundle: the full draft-emails text lives
// in dist/skills for the host to surface later.
cpSync('src/skills', 'dist/skills', { recursive: true });
