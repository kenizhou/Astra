/**
 * JSONL protocol between the Rust host and this sidecar: one JSON object per
 * line in both directions, stderr carries human logs only. Every wire field
 * is snake_case and pinned by the shared fixtures under
 * src/fixtures/protocol, parsed here and by the Rust mirror's serde in its
 * include_str test, so the two sides cannot drift. A fixture line is
 * byte-identical to a wire line.
 */

/** Wire protocols a tier config may name; pi-ai ships an adapter per value. */
export type ModelApi = 'openai-completions' | 'anthropic-messages';

/** Per-tier model endpoint config, delivered on the init envelope. Model API
 *  keys live in sidecar memory only and never reach a log line. */
export interface ModelConfig {
  api: ModelApi;
  base_url: string;
  model: string;
  api_key?: string;
}

/** One policy table row as the host delivers it on init. */
export interface PermissionPolicy {
  level: 'auto' | 'notify' | 'confirm' | 'confirm_preview';
  allowlist?: boolean;
}

export type InCommand =
  | {
      type: 'init';
      harness: string;
      /** Path to the mock transcript fixture; the mock harness only. */
      mock_fixture?: string;
      /** Absolute astra-cli path; the empty string means unresolved. */
      cli_path: string;
      data_dir: string;
      /** tier name to endpoint config; the adapter registers one model. */
      model_configs?: Record<string, ModelConfig>;
      /** The permission policy table; absent means every tool fails closed. */
      policy?: Record<string, PermissionPolicy>;
    }
  | {
      type: 'prompt';
      id: string;
      session_id: string;
      text: string;
      /** The turn's correlation id, generated by the host; it rides every
       *  tool spawn and the llm_call ledger row (the traceability rule). */
      correlation_id: string;
    }
  | { type: 'abort'; id: string; session_id: string }
  | { type: 'command'; id: string; name: string; args: Record<string, unknown> }
  | { type: 'permission_response'; id: string; approved: boolean; always_allow: boolean };

export type AgentEventPayload =
  | { kind: 'text_delta'; text: string }
  | { kind: 'tool_call'; name: string; args: unknown; tool_call_id: string }
  | { kind: 'state'; state: string }
  | { kind: 'tool_result'; tool_call_id: string; name: string; status: string; output?: string };

/** One LLM API call's ledger row, emitted per call. Wire shape: snake_case
 *  inside the `call` payload, mirroring the ledger columns. */
export interface LlmCallData {
  session_id: string;
  prompt_id?: string;
  correlation_id?: string;
  model: string;
  tier: string;
  caller: string;
  prompt_tokens: number;
  completion_tokens: number;
  cache_read_tokens: number;
  cache_write_tokens: number;
  duration_ms: number;
  status: 'ok' | 'error';
  error?: string;
}

export type ToolResultStatus = 'ok' | 'error' | 'rejected' | 'skipped';

export type OutEnvelope =
  | { type: 'ready'; models: string[]; harnesses: string[] }
  | { type: 'event'; session_id: string; event: AgentEventPayload }
  | { type: 'done'; id: string }
  | { type: 'error'; id: string | null; message: string }
  | { type: 'result'; id: string; value: unknown }
  | { type: 'llm_call'; call: LlmCallData }
  | {
      type: 'permission_request';
      id: string;
      tool_call_id: string;
      tool: string;
      level: 'confirm' | 'confirm_preview';
      args: Record<string, unknown>;
      preview?: unknown;
    }
  | {
      type: 'tool_result';
      tool_call_id: string;
      tool: string;
      status: ToolResultStatus;
      output?: string;
    };

function isString(v: unknown): v is string {
  return typeof v === 'string';
}

function isStringArray(v: unknown): v is string[] {
  return Array.isArray(v) && v.every(isString);
}

function isObject(v: unknown): v is Record<string, unknown> {
  return typeof v === 'object' && v !== null && !Array.isArray(v);
}

const MODEL_APIS: readonly string[] = ['openai-completions', 'anthropic-messages'];
const POLICY_LEVELS: readonly string[] = ['auto', 'notify', 'confirm', 'confirm_preview'];

/** Parse the init envelope's model_configs. Returns null on any malformed
 *  entry: a half-parsed endpoint config must never reach the adapter, where
 *  a missing base_url would surface as a confusing runtime failure. */
function parseModelConfigs(v: unknown): Record<string, ModelConfig> | null {
  if (!isObject(v)) return null;
  const out: Record<string, ModelConfig> = {};
  for (const [tier, raw] of Object.entries(v)) {
    if (!isObject(raw)) return null;
    if (!isString(raw.base_url) || !isString(raw.model)) return null;
    if (raw.api !== undefined && !MODEL_APIS.includes(raw.api as string)) return null;
    const cfg: ModelConfig = {
      api: (raw.api as ModelApi | undefined) ?? 'openai-completions',
      base_url: raw.base_url,
      model: raw.model,
    };
    if (isString(raw.api_key)) cfg.api_key = raw.api_key;
    out[tier] = cfg;
  }
  return out;
}

/** Parse the init envelope's policy table. Returns null on any malformed
 *  row: the bridge fails closed per tool, but a malformed table is a host
 *  bug and the init line is rejected outright, never silently half-applied. */
function parsePolicy(v: unknown): Record<string, PermissionPolicy> | null {
  if (!isObject(v)) return null;
  const out: Record<string, PermissionPolicy> = {};
  for (const [tool, raw] of Object.entries(v)) {
    if (!isObject(raw)) return null;
    if (!isString(raw.level) || !POLICY_LEVELS.includes(raw.level)) return null;
    if (raw.allowlist !== undefined && typeof raw.allowlist !== 'boolean') return null;
    const entry: PermissionPolicy = { level: raw.level as PermissionPolicy['level'] };
    if (typeof raw.allowlist === 'boolean') entry.allowlist = raw.allowlist;
    out[tool] = entry;
  }
  return out;
}

/** Parse one stdin line into an InCommand. Returns null on any malformed
 *  input: the caller logs a warning to stderr and skips the line. Malformed
 *  never means guess. */
export function parseCommand(line: string): InCommand | null {
  let raw: unknown;
  try {
    raw = JSON.parse(line);
  } catch {
    return null;
  }
  if (typeof raw !== 'object' || raw === null) return null;
  const o = raw as Record<string, unknown>;
  switch (o.type) {
    case 'init': {
      // cli_path and data_dir are required Rust fields; the empty string is
      // allowed (the host sends it when it cannot resolve the binary).
      if (!isString(o.harness) || !isString(o.cli_path) || !isString(o.data_dir)) {
        return null;
      }
      const cmd: InCommand = {
        type: 'init',
        harness: o.harness,
        cli_path: o.cli_path,
        data_dir: o.data_dir,
      };
      if (isString(o.mock_fixture)) cmd.mock_fixture = o.mock_fixture;
      if (o.model_configs !== undefined) {
        const configs = parseModelConfigs(o.model_configs);
        if (!configs) return null;
        cmd.model_configs = configs;
      }
      if (o.policy !== undefined) {
        const policy = parsePolicy(o.policy);
        if (!policy) return null;
        cmd.policy = policy;
      }
      return cmd;
    }
    case 'prompt': {
      if (
        !isString(o.id) ||
        !isString(o.session_id) ||
        !isString(o.text) ||
        !isString(o.correlation_id)
      ) {
        return null;
      }
      return {
        type: 'prompt',
        id: o.id,
        session_id: o.session_id,
        text: o.text,
        correlation_id: o.correlation_id,
      };
    }
    case 'abort': {
      if (!isString(o.id) || !isString(o.session_id)) return null;
      return { type: 'abort', id: o.id, session_id: o.session_id };
    }
    case 'command': {
      if (!isString(o.id) || !isString(o.name)) return null;
      if (!isObject(o.args)) return null;
      return { type: 'command', id: o.id, name: o.name, args: o.args };
    }
    case 'permission_response': {
      if (!isString(o.id)) return null;
      if (typeof o.approved !== 'boolean' || typeof o.always_allow !== 'boolean') return null;
      return {
        type: 'permission_response',
        id: o.id,
        approved: o.approved,
        always_allow: o.always_allow,
      };
    }
    default:
      return null;
  }
}

function isValidEventPayload(v: unknown): boolean {
  if (!isObject(v)) return false;
  switch (v.kind) {
    case 'text_delta':
      return isString(v.text);
    case 'tool_call':
      return isString(v.name) && isString(v.tool_call_id);
    case 'state':
      return isString(v.state);
    case 'tool_result':
      return (
        isString(v.tool_call_id) &&
        isString(v.name) &&
        isString(v.status) &&
        (v.output === undefined || isString(v.output))
      );
    default:
      return false;
  }
}

function isValidLlmCallData(v: unknown): boolean {
  if (!isObject(v)) return false;
  return (
    isString(v.session_id) &&
    isString(v.model) &&
    isString(v.tier) &&
    isString(v.caller) &&
    typeof v.prompt_tokens === 'number' &&
    typeof v.completion_tokens === 'number' &&
    typeof v.cache_read_tokens === 'number' &&
    typeof v.cache_write_tokens === 'number' &&
    typeof v.duration_ms === 'number' &&
    (v.status === 'ok' || v.status === 'error') &&
    (v.prompt_id === undefined || isString(v.prompt_id)) &&
    (v.correlation_id === undefined || isString(v.correlation_id)) &&
    (v.error === undefined || isString(v.error))
  );
}

/** Structural validation of one outbound envelope. The mirror of what the
 *  Rust side's serde deserialiser enforces; the fixture test holds both
 *  sides to the same shapes. */
export function isValidEnvelope(v: unknown): boolean {
  if (!isObject(v)) return false;
  switch (v.type) {
    case 'ready':
      return isStringArray(v.models) && isStringArray(v.harnesses);
    case 'event':
      return isString(v.session_id) && isValidEventPayload(v.event);
    case 'done':
      return isString(v.id);
    case 'error':
      return (v.id === null || isString(v.id)) && isString(v.message);
    case 'result':
      return isString(v.id) && 'value' in v;
    case 'llm_call':
      return isValidLlmCallData(v.call);
    case 'permission_request':
      return (
        isString(v.id) &&
        isString(v.tool_call_id) &&
        isString(v.tool) &&
        (v.level === 'confirm' || v.level === 'confirm_preview') &&
        isObject(v.args)
        // preview is renderable payload of any shape; its presence is free.
      );
    case 'tool_result':
      return (
        isString(v.tool_call_id) &&
        isString(v.tool) &&
        (v.status === 'ok' ||
          v.status === 'error' ||
          v.status === 'rejected' ||
          v.status === 'skipped') &&
        (v.output === undefined || isString(v.output))
      );
    default:
      return false;
  }
}

/** Write one stdout envelope line. On EPIPE the host is gone: exit(0) so we
 *  never linger as a zombie (the Rust side kills on drop). */
export function writeEnvelope(env: OutEnvelope): void {
  try {
    process.stdout.write(JSON.stringify(env) + '\n');
  } catch (e) {
    if ((e as NodeJS.ErrnoException).code === 'EPIPE') process.exit(0);
    throw e;
  }
}
